"""Regenerate every table in docs/audit_2026-10.md from the raw result files.

Reads only files under outputs/results/ and outputs/mia/ and outputs/comm/ (the raw, preserved
experiment outputs); writes docs/audit_tables.md. Nothing is typed in by hand.

Usage: uv run python scripts/make_audit_tables.py
"""
from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
R = REPO / "outputs/results"
OUT = REPO / "docs/audit_tables.md"


def pm(x: dict, d: int = 3) -> str:
    """mean ± sample std (n-1). Result files written before the sample-std field existed only carry
    the raw per-seed `values`, so the sample std is recomputed from them."""
    import numpy as np
    n = x.get("n_seeds", 1)
    if n <= 1:
        return f"{x['mean']:.{d}f}"
    sd = x["sample_std"] if "sample_std" in x else float(np.std(x["values"], ddof=1))
    return f"{x['mean']:.{d}f} ± {sd:.{d}f}"


def table(title: str, header: list[str], rows: list[list[str]], note: str = "") -> str:
    out = [f"### {title}", "", "| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out) + ("\n\n" + note if note else "") + "\n"


def main() -> None:
    parts = ["# Audit tables (generated)\n",
             "Generated by `scripts/make_audit_tables.py` from raw files in `outputs/`. "
             "Mean ± **sample** std (n−1) over seeds {42, 123, 2024}. Do not edit by hand.\n"]

    fa = json.loads((R / "exp_final_ablation.json").read_text())["rows"]
    names = {"centralized": "Centralized (pooled)", "fedavg_original": "FedAvg (project recipe)",
             "fedavg_secagg_original": "FedAvg + SecAgg+ (project recipe)", "fedavg_matched": "FedAvg, DP-matched recipe (no augmentation, no class weights)",
             "secagg_matched": "FedAvg + SecAgg+ (DP-matched recipe, real Flower SecAgg+)",
             "secagg_dp_eps4_row6": "Row 6, first campaign (same training; ε reporting defect F11)",
             "secagg_dp_eps4_row6_v2": "Row 6 — FedAvg + SecAgg+ + DP ε=4 (tuned recipe, real Flower SecAgg+; simulation, no TLS)"}
    for e in ("1", "2", "4", "8"):
        names[f"dp_original_eps{e}"] = f"FedAvg + DP ε={e} (original recipe)"
        names[f"dp_tuned_eps{e}"] = f"FedAvg + DP ε={e} (validation-tuned recipe)"
    rows = [[names[k], pm(fa[k]["auroc_macro"]), pm(fa[k]["auroc_A"]), pm(fa[k]["auroc_B"]), pm(fa[k]["auroc_C"]), pm(fa[k]["auroc_pooled"]),
             pm(fa[k]["sensitivity_spec90local_macro"]), pm(fa[k]["specificity_spec90local_macro"])] for k in names if k in fa]
    parts.append(table("T1. Ablation under one protocol (test splits)",
                       ["Configuration", "Macro AUROC", "AUROC A", "AUROC B", "AUROC C", "Pooled AUROC", "Sens @ local 90%-spec thr.", "Spec"], rows,
                       "Macro AUROC = mean of the three within-hospital test AUROCs. Operating points use thresholds chosen on each hospital's VALIDATION split only."))

    pe = json.loads((R / "audit_per_hospital_eval.json").read_text())
    rows = []
    for k, r in pe["scores"]["natural"].items():
        if r:
            rows.append([k] + [pm(r[f"auroc_{h}"]) for h in ("A", "B", "C", "pooled")])
    parts.append(table("T2. Every checkpoint scored on every hospital's own test split and on the pooled split (natural regime)",
                       ["Model", "Test A", "Test B", "Test C", "Pooled"], rows,
                       "Local models are evaluated on the hospitals they never saw as well; the original ablation's row 1 averaged only the diagonal."))

    mia = json.loads((R / "audit_mia_existing.json").read_text())
    rows = [[k, pm(v["auc_train_vs_test"], 4), pm(v["auc_train_vs_val"], 4), pm(v["auc_val_vs_test_NEGATIVE_CONTROL"], 4),
             pm(v["auc_class_balanced_train_vs_test"], 4), pm(v["tpr_at_1pct_fpr"], 4)] for k, v in mia.items()]
    parts.append(table("T3. Original loss-attack, re-audited",
                       ["Model", "AUROC train vs test", "train vs val", "NEGATIVE CONTROL val vs test", "class-balanced", "TPR @ 1% FPR"], rows,
                       "The negative control compares two non-member sets; a valid attack must score 0.5 there."))

    rows = []
    for tag in ("nondp", "dp_eps1", "dp_eps4", "dp_eps8"):
        f = REPO / "outputs/mia" / tag / "analysis.json"
        if f.exists():
            a = json.loads(f.read_text())
            for atk in ("global_threshold_attack", "lira_online_fixed_var"):
                x = a[atk]; t = x["tpr_at_fpr"]
                rows.append([tag, atk, str(a["n_models"]), f"{x['auroc']:.4f}", f"{t['0.001']:.4f}", f"{t['0.01']:.4f}", f"{t['0.1']:.4f}",
                             f"{x['epsilon_lower_bound_indicative']['epsilon_lb']:.2f}"])
    if rows:
        parts.append(table("T4. Shadow-model membership inference (recipe audit, ~half-size training data)",
                           ["Recipe", "Attack", "Shadow models", "AUROC", "TPR@0.1%FPR", "TPR@1%FPR", "TPR@10%FPR", "Indicative ε lower bound"], rows,
                           "Chance: AUROC 0.5, TPR = FPR. The ε lower bound is indicative (dependent trials) and can only falsify a claimed ε, never certify one."))

    comm_dir = REPO / "outputs/comm"
    rows = []
    for f in sorted(comm_dir.glob("*.jsonl")) if comm_dir.exists() else []:
        by_run: dict = {}
        for line in f.read_text().splitlines():
            r = json.loads(line)
            by_run.setdefault(r.get("run_id", "?"), []).append(r)
        for rid, rs in by_run.items():
            nodes = {r["node"] for r in rs}; rnds = {r["group_id"] for r in rs}
            cr = len(nodes) * len(rnds)
            # Records without a run_id are the six runs of the first campaign, which all landed in the first run's
            # log (the simulation SuperLink process keeps its first environment); they are summed, so divide by 6.
            div = 6 if rid == "?" else 1
            rows.append([f"{f.stem}:{'six runs of the first campaign (÷6)' if rid == '?' else 'run ' + rid[-6:]}", str(cr),
                         f"{sum(r['bytes_in'] for r in rs) / cr / div / 1e6:.2f}", f"{sum(r['bytes_out'] for r in rs) / cr / div / 1e6:.2f}",
                         f"{len(rs) / cr / div:.1f}"])
    if rows:
        parts.append(table("T5. SecAgg+ application-layer bytes per client per round",
                           ["Source", "client-rounds", "MB received", "MB sent (upload)", "messages"], rows,
                           "Flower record payload bytes (a lower bound: excludes gRPC/TLS framing). Plain FedAvg uploads 1.05 MB (263 K float32 parameters) per client per round. "
                           "Per round, one SecAgg+ client sends: setup 0.4 KB, share keys 1.2 KB, masked vector 2.10 MB (int64-encoded), unmask 0.2 KB, plus the evaluate reply; "
                           "the control messages are a few KB, so the overhead is the 2x integer encoding of the update, not the key exchange."))
    OUT.write_text("\n".join(parts))
    print(f"written {OUT}")


if __name__ == "__main__":
    main()
